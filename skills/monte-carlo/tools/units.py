#!/usr/bin/env python3
"""Units for a model, checked by pint. JavaScript models run in plain SI for speed, so this is where units are enforced.

  units.py compile <coefficients.source.json> <coefficients.js>
      Parse every coefficient's unit with pint, convert it to SI, and write a JavaScript module the model imports.
      A value with a wrong or unknown unit stops the build.

  units.py check <model.js>
      Ask the engine for every parameter, input and metric of a model and parse each declared unit.

Needs pint: python3 -m pip install pint
"""
import json
import subprocess
import sys
from pathlib import Path

import pint

ureg = pint.UnitRegistry()
ALIASES = {None: "dimensionless", "": "dimensionless", "-": "dimensionless", "x": "dimensionless", "%": "percent", "N m": "N*m", "g m": "g*m", "kg/m3": "kg/m**3"}

# what each coefficient's property must be, so a modulus typed in kg fails here and not in a simulation
DIMENSIONS = {
    "density": "[mass]/[length]**3", "rho_air": "[mass]/[length]**3",
    "E": "[mass]/[length]/[time]**2",
    "nu_air": "[length]**2/[time]",
    "nu": "", "cor": "", "mu_s": "", "mu_k": "", "crr": "", "cd": "", "cl": "",
}


def parse(unit):
    return ureg.parse_units(ALIASES.get(unit, unit))


def compile_library(src, dst):
    entries = json.loads(Path(src).read_text())
    out = {}
    problems = []
    for e in entries:
        try:
            unit = parse(e.get("unit"))
            prop = e["id"].rsplit(".", 1)[1]
            want = DIMENSIONS.get(prop)
            if want is not None and not ureg.Quantity(1, unit).check(want or "[]"):
                problems.append(f"{e['id']}: {e.get('unit')} is not {want or 'dimensionless'}")
                continue
            si = lambda v: None if v is None else ureg.Quantity(v, unit).to_base_units().magnitude
            base = ureg.Quantity(1, unit).to_base_units().units
            out[e["id"]] = {
                "low": si(e.get("low")), "typical": si(e.get("typical")), "high": si(e.get("high")),
                "si": f"{base:~}" or "dimensionless", "given": f"{e.get('typical')} {e.get('unit')}",
                "source": e.get("source"), "note": e.get("note"), "condition": e.get("condition"),
            }
        except Exception as err:  # every bad entry gets reported, not just the first
            problems.append(f"{e.get('id')}: {err}")
    if problems:
        sys.exit("unit problems:\n  " + "\n  ".join(problems))
    Path(dst).write_text(
        "// Generated by skills/monte-carlo/tools/units.py from coefficients.source.json. Do not edit: all values are SI.\n"
        f"export const COEFFICIENTS = {json.dumps(out, indent=1)};\n"
    )
    print(f"{len(out)} coefficients converted to SI by pint, {dst}")


def check_model(model):
    cli = Path(__file__).resolve().parent.parent / "engine" / "cli.js"
    data = json.loads(subprocess.check_output(["node", str(cli), "inspect", model, "--json"], text=True))
    bad = []
    n = 0
    for kind in ("parameters", "inputs", "metrics"):
        for item in data[kind]:
            n += 1
            try:
                parse(item.get("unit"))
            except Exception as err:
                bad.append(f"{kind} {item['id']}: {item.get('unit')!r}: {err}")
    if bad:
        sys.exit("unit problems:\n  " + "\n  ".join(bad))
    print(f"{data['name']}: all {n} declared units parse")


if __name__ == "__main__":
    if len(sys.argv) >= 4 and sys.argv[1] == "compile":
        compile_library(sys.argv[2], sys.argv[3])
    elif len(sys.argv) >= 3 and sys.argv[1] == "check":
        check_model(sys.argv[2])
    else:
        sys.exit(__doc__)
